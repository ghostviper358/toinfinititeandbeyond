package com.ghostviper358.toinfinititeandbeyond;

import net.minecraft.client.renderer.RenderType;
import net.minecraft.resources.ResourceLocation;
import software.bernie.geckolib.model.GeoModel;
import software.bernie.geckolib.renderer.base.GeoRenderState;

/**
 * Points GeckoLib at the Black Hole Arm Cannon's 3D model and texture.
 *
 * - Model:     assets/toinfinititeandbeyond/geckolib/models/item/black_hole_arm_cannon.geo.json,
 *              generated from a list of cubes by gen_black_hole_arm_cannon_model.py
 * - Texture:   assets/toinfinititeandbeyond/textures/item/black_hole_arm_cannon.png, generated by
 *              gen_black_hole_arm_cannon_texture.py
 * - Animation: an empty file - the parts are moved in code (see BlackHoleArmCannonRenderer).
 */
public class BlackHoleArmCannonModel extends GeoModel<BlackHoleArmCannonItem> {

    private static final ResourceLocation MODEL = ResourceLocation.fromNamespaceAndPath(
        ToInfinititeAndBeyond.MOD_ID, "item/black_hole_arm_cannon");
    private static final ResourceLocation TEXTURE = ResourceLocation.fromNamespaceAndPath(
        ToInfinititeAndBeyond.MOD_ID, "textures/item/black_hole_arm_cannon.png");
    private static final ResourceLocation ANIMATIONS = ResourceLocation.fromNamespaceAndPath(
        ToInfinititeAndBeyond.MOD_ID, "item/black_hole_arm_cannon");

    @Override
    public ResourceLocation getModelResource(GeoRenderState renderState) {
        return MODEL;
    }

    @Override
    public ResourceLocation getTextureResource(GeoRenderState renderState) {
        return TEXTURE;
    }

    @Override
    public ResourceLocation getAnimationResource(BlackHoleArmCannonItem animatable) {
        return ANIMATIONS;
    }

    /** See-through rendering, so the black hole's purple outside is a faint glow around its black inside. */
    @Override
    public RenderType getRenderType(GeoRenderState renderState, ResourceLocation texture) {
        return RenderType.entityTranslucent(texture);
    }
}
