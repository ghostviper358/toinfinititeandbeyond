package com.ghostviper358.toinfinititeandbeyond;

import net.minecraft.client.renderer.RenderType;
import net.minecraft.resources.ResourceLocation;
import software.bernie.geckolib.model.GeoModel;
import software.bernie.geckolib.renderer.base.GeoRenderState;

/**
 * Points GeckoLib at the Universal Core's 3D model and texture. See
 * docs/requirements/universal_core.md.
 *
 * - Model:     assets/toinfinititeandbeyond/geckolib/models/item/universal_core.geo.json
 * - Texture:   assets/toinfinititeandbeyond/textures/item/universal_core_3d.png - an animated
 *              frame-strip (the swirling core), generated by gen_universal_core_texture.py.
 * - Animation: an empty file - the rings are turned in code (see UniversalCoreRenderer).
 */
public class UniversalCoreModel extends GeoModel<UniversalCoreItem> {

    private static final ResourceLocation MODEL = ResourceLocation.fromNamespaceAndPath(
        ToInfinititeAndBeyond.MOD_ID, "item/universal_core");
    private static final ResourceLocation TEXTURE = ResourceLocation.fromNamespaceAndPath(
        ToInfinititeAndBeyond.MOD_ID, "textures/item/universal_core_3d.png");
    private static final ResourceLocation ANIMATIONS = ResourceLocation.fromNamespaceAndPath(
        ToInfinititeAndBeyond.MOD_ID, "item/universal_core");

    @Override
    public ResourceLocation getModelResource(GeoRenderState renderState) {
        return MODEL;
    }

    @Override
    public ResourceLocation getTextureResource(GeoRenderState renderState) {
        return TEXTURE;
    }

    @Override
    public ResourceLocation getAnimationResource(UniversalCoreItem animatable) {
        return ANIMATIONS;
    }

    /** See-through rendering, so the golden aura shell is a faint glow rather than a solid box. */
    @Override
    public RenderType getRenderType(GeoRenderState renderState, ResourceLocation texture) {
        return RenderType.entityTranslucent(texture);
    }
}
